"""Regenerate ``waldur_core/core/countries.py`` from the pycountry package.

The generated module is the only copy of the ISO 3166-1 table Waldur ships.
Run this when ISO 3166-1 changes and a newer pycountry release carries it:

    uvx --from pycountry python scripts/generate_countries.py

Then review the diff: country names are user-visible on the API and in the
generated frontend settings description.
"""

import json
import pathlib
import sys

try:
    import pycountry
except ImportError:
    sys.exit("pycountry is not installed; run via `uvx --from pycountry python ...`")

TARGET = (
    pathlib.Path(__file__).resolve().parent.parent
    / "src"
    / "waldur_core"
    / "core"
    / "countries.py"
)

HEADER = '''"""ISO 3166-1 alpha-2 country codes and English short names.

Generated by ``scripts/generate_countries.py`` from pycountry {version}; do not
edit by hand. The data originates from the Debian iso-codes project
(LGPL-2.1, https://salsa.debian.org/iso-codes-team/iso-codes) and is
reproduced here as a factual list of codes and names.
"""

ISO_3166_1: list[tuple[str, str]] = [
'''

rows = [(c.alpha_2, c.name) for c in pycountry.countries]
version = getattr(pycountry, "__version__", "unknown")
body = "".join(
    f"    ({json.dumps(code)}, {json.dumps(name, ensure_ascii=False)}),\n"
    for code, name in rows
)
TARGET.write_text(HEADER.format(version=version) + body + "]\n")
print(f"wrote {len(rows)} rows to {TARGET}")
